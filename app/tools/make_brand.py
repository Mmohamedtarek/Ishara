#!/usr/bin/env python3
"""Generates every app icon and native launch image from ONE vector source,
app/ishara_app/brand/ishara_mark.svg (the prototype's `.mark` + logo hand).

Writes (overwrites):
  Android  res/mipmap-anydpi-v26/ic_launcher.xml        adaptive icon
           res/drawable/ic_launcher_{background,foreground,monochrome}.xml  vectors
           res/mipmap-{m,h,xh,xxh,xxxh}dpi/ic_launcher.png   legacy icons (rasterized)
           res/drawable/launch_mark.xml, splash_icon.xml  launch / Android 12+ splash vectors
           res/values*/colors.xml (ishara_bg = prototype --bg, light / dark)
  iOS      Assets.xcassets/AppIcon.appiconset/*.png  (opaque, full-bleed: iOS rounds the corners)
           Assets.xcassets/LaunchImage.imageset/*.png  (the mark, 88 pt)
           Assets.xcassets/LaunchBackground.colorset/Contents.json  (light / dark)
Rasterizing uses the system Chrome through Playwright (as the other review tools).

Usage (from app/tools): .venv/bin/python make_brand.py
"""
from __future__ import annotations

import io
import json
import re
import struct
import zlib
from pathlib import Path
from xml.etree import ElementTree as ET

from playwright.sync_api import sync_playwright

HERE = Path(__file__).resolve().parent
APP = HERE.parent / "ishara_app"
SRC = APP / "brand" / "ishara_mark.svg"
RES = APP / "android" / "app" / "src" / "main" / "res"
XCA = APP / "ios" / "Runner" / "Assets.xcassets"

# prototype --bg (light / dark): the native launch background and the
# Android 12+ splash background, so nothing flashes before Flutter draws.
BG_LIGHT = "#F4F2EC"
BG_DARK = "#121318"
STOPS = [(0, "#4B5BD6"), (0.55, "#3446C9"), (1, "#24309A")]
HAND_RATIO = 48 / 88   # hand size / mark size (prototype: 48 px in 88 px)

NS = {"s": "http://www.w3.org/2000/svg"}


def hand_paths() -> list[str]:
    root = ET.parse(SRC).getroot()
    g = root.find(".//s:g[@id='hand']", NS)
    paths = [p.get("d") for p in g.findall("s:path", NS)]
    assert paths and all(paths), "hand paths missing in the source SVG"
    return paths


def vector(size_dp: float, viewport: float, body: str, aapt: bool = False) -> str:
    ns = ' xmlns:aapt="http://schemas.android.com/aapt"' if aapt else ""
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by app/tools/make_brand.py from brand/ishara_mark.svg. Do not edit. -->\n"
        f'<vector xmlns:android="http://schemas.android.com/apk/res/android"{ns}\n'
        f'    android:width="{size_dp:g}dp" android:height="{size_dp:g}dp"\n'
        f'    android:viewportWidth="{viewport:g}" android:viewportHeight="{viewport:g}">\n'
        f"{body}</vector>\n"
    )


def gradient(x0: float, y0: float, x1: float, y1: float) -> str:
    items = "".join(f'                <item android:offset="{o:g}" android:color="{c}"/>\n' for o, c in STOPS)
    return (
        '        <aapt:attr name="android:fillColor">\n'
        f'            <gradient android:type="linear" android:startX="{x0:g}" android:startY="{y0:g}"'
        f' android:endX="{x1:g}" android:endY="{y1:g}">\n'
        f"{items}"
        "            </gradient>\n"
        "        </aapt:attr>\n"
    )


def rounded_rect(x: float, y: float, s: float, r: float) -> str:
    return (f"M{x + r:g},{y:g}H{x + s - r:g}A{r:g},{r:g} 0 0 1 {x + s:g},{y + r:g}V{y + s - r:g}"
            f"A{r:g},{r:g} 0 0 1 {x + s - r:g},{y + s:g}H{x + r:g}A{r:g},{r:g} 0 0 1 {x:g},{y + s - r:g}"
            f"V{y + r:g}A{r:g},{r:g} 0 0 1 {x + r:g},{y:g}Z")


def hand_group(x: float, y: float, size: float, color: str = "#FFFFFFFF") -> str:
    k = size / 24
    paths = "".join(
        f'        <path android:pathData="{d}" android:strokeColor="{color}" android:strokeWidth="2.4"\n'
        '            android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000"/>\n'
        for d in hand_paths()
    )
    return (f'    <group android:translateX="{x:g}" android:translateY="{y:g}" '
            f'android:scaleX="{k:g}" android:scaleY="{k:g}">\n{paths}    </group>\n')


def mark_body(x: float, y: float, s: float) -> str:
    r = s * 26 / 88
    hs = s * HAND_RATIO
    return (
        f'    <path android:pathData="{rounded_rect(x, y, s, r)}">\n'
        f"{gradient(x, y, x + s, y + s)}"
        "    </path>\n"
        + hand_group(x + (s - hs) / 2, y + (s - hs) / 2, hs)
    )


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    print("wrote", path.relative_to(APP))


def android() -> None:
    # Adaptive icon: 108 dp layers; the visible mask is about the middle 72 dp
    # and the safe zone a 66 dp circle. The hand keeps the mark's ratio to
    # the visible part (48 / 88 of 72 dp ≈ 39 dp), well inside the safe zone.
    write(RES / "drawable" / "ic_launcher_background.xml", vector(108, 108,
          '    <path android:pathData="M0,0H108V108H0Z">\n' + gradient(0, 0, 108, 108) + "    </path>\n", aapt=True))
    hs = 72 * HAND_RATIO
    fg = hand_group((108 - hs) / 2, (108 - hs) / 2, hs)
    write(RES / "drawable" / "ic_launcher_foreground.xml", vector(108, 108, fg))
    write(RES / "drawable" / "ic_launcher_monochrome.xml", vector(108, 108, fg))
    write(RES / "mipmap-anydpi-v26" / "ic_launcher.xml",
          '<?xml version="1.0" encoding="utf-8"?>\n'
          "<!-- Generated by app/tools/make_brand.py. -->\n"
          '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
          '    <background android:drawable="@drawable/ic_launcher_background"/>\n'
          '    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n'
          '    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n'
          "</adaptive-icon>\n")
    # Launch: the mark at its prototype size (88 dp) on --bg.
    write(RES / "drawable" / "launch_mark.xml", vector(88, 88, mark_body(0, 0, 88), aapt=True))
    # Android 12+ splash icon without background: 288 dp, content within a
    # 192 dp circle; the mark stays 88 dp, centred.
    write(RES / "drawable" / "splash_icon.xml", vector(288, 288, mark_body(100, 100, 88), aapt=True))
    for folder, bg in (("values", BG_LIGHT), ("values-night", BG_DARK)):
        write(RES / folder / "colors.xml",
              '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by app/tools/make_brand.py: the prototype background (bg token). -->\n'
              f'<resources>\n    <color name="ishara_bg">{bg}</color>\n</resources>\n')


def svg_markup(size: int, *, rounded: bool, bg_only_square: bool = False) -> str:
    src = SRC.read_text(encoding="utf-8")
    src = re.sub(r"<!--.*?-->", "", src, flags=re.S)
    if not rounded:
        src = src.replace('rx="26" ry="26"', 'rx="0" ry="0"')
    return src.replace('width="88" height="88"', f'width="{size}" height="{size}"')


def png_strip_alpha(png: bytes) -> bytes:
    """RGBA → RGB (iOS app icons must have no alpha channel)."""
    data = io.BytesIO(png)
    assert data.read(8) == b"\x89PNG\r\n\x1a\n"
    idat = b""
    while True:
        ln, = struct.unpack(">I", data.read(4))
        typ = data.read(4)
        body = data.read(ln)
        data.read(4)
        if typ == b"IHDR":
            w, h, depth, ctype = struct.unpack(">IIBB", body[:10])
        elif typ == b"IDAT":
            idat += body
        elif typ == b"IEND":
            break
    if ctype == 2:
        return png
    assert depth == 8 and ctype == 6, (depth, ctype)
    raw = zlib.decompress(idat)
    stride = w * 4
    rows = []
    prev = bytearray(stride)
    pos = 0
    for _ in range(h):
        f = raw[pos]
        line = bytearray(raw[pos + 1:pos + 1 + stride])
        pos += 1 + stride
        for i in range(stride):
            a = line[i - 4] if i >= 4 else 0
            b = prev[i]
            c = prev[i - 4] if i >= 4 else 0
            if f == 1:
                line[i] = (line[i] + a) & 255
            elif f == 2:
                line[i] = (line[i] + b) & 255
            elif f == 3:
                line[i] = (line[i] + ((a + b) >> 1)) & 255
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else (b if pb <= pc else c))) & 255
        rows.append(b"\x00" + bytes(line[j] for j in range(stride) if j % 4 != 3))
        prev = line

    def chunk(t: bytes, d: bytes) -> bytes:
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)

    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(b"".join(rows), 9)) + chunk(b"IEND", b""))


def render(page, markup: str, size: int, transparent: bool) -> bytes:
    page.set_viewport_size({"width": size, "height": size})
    page.set_content(f"<html><body style='margin:0;background:transparent'>{markup}</body></html>")
    return page.screenshot(clip={"x": 0, "y": 0, "width": size, "height": size}, omit_background=transparent)


def rasters() -> None:
    with sync_playwright() as pw:
        b = pw.chromium.launch(channel="chrome")
        page = b.new_page(device_scale_factor=1)
        # Android legacy icons (pre-8.0 launchers): the rounded mark.
        for folder, px in (("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)):
            out = RES / f"mipmap-{folder}" / "ic_launcher.png"
            out.write_bytes(render(page, svg_markup(px, rounded=True), px, transparent=True))
            print("wrote", out.relative_to(APP))
        # iOS app icons: full-bleed square, opaque.
        icon_set = XCA / "AppIcon.appiconset"
        contents = json.loads((icon_set / "Contents.json").read_text())
        for img in contents["images"]:
            pts = float(img["size"].split("x")[0])
            px = round(pts * int(img["scale"].rstrip("x")))
            out = icon_set / img["filename"]
            out.write_bytes(png_strip_alpha(render(page, svg_markup(px, rounded=False), px, transparent=False)))
            print("wrote", out.relative_to(APP))
        # iOS launch image: the rounded mark, 88 pt.
        li = XCA / "LaunchImage.imageset"
        for name, px in (("LaunchImage.png", 88), ("LaunchImage@2x.png", 176), ("LaunchImage@3x.png", 264)):
            (li / name).write_bytes(render(page, svg_markup(px, rounded=True), px, transparent=True))
            print("wrote", (li / name).relative_to(APP))
        b.close()


def ios_colors() -> None:
    def rgb(hexc: str) -> dict:
        return {"red": f"0x{hexc[1:3]}", "green": f"0x{hexc[3:5]}", "blue": f"0x{hexc[5:7]}", "alpha": "1.000"}

    contents = {
        "colors": [
            {"idiom": "universal", "color": {"color-space": "srgb", "components": rgb(BG_LIGHT)}},
            {"idiom": "universal", "appearances": [{"appearance": "luminosity", "value": "dark"}],
             "color": {"color-space": "srgb", "components": rgb(BG_DARK)}},
        ],
        "info": {"author": "xcode", "version": 1},
    }
    write(XCA / "LaunchBackground.colorset" / "Contents.json", json.dumps(contents, indent=2) + "\n")


def main() -> int:
    android()
    ios_colors()
    rasters()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
