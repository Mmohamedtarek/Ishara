#!/usr/bin/env python3
"""Port the prototype's ICONS (design/prototype.html) into lib/core/ui/ishara_icon_data.dart.

Each icon becomes a full SVG string (24x24 viewBox, stroke = currentColor, the prototype's
stroke width), rendered by IsharaIcon with flutter_svg. Run strip_prototype.py first.
Usage: python3 app/tools/extract_icons.py
"""
import pathlib
import re
import sys

from proto_common import REPO, prototype_src
OUT = REPO / "app" / "ishara_app" / "lib" / "core" / "ui" / "ishara_icon_data.dart"


def svg(body: str, width: str) -> str:
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
            f'stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round">{body}</svg>')


def main() -> int:
    src = prototype_src()
    s = src.read_text(encoding="utf-8")
    block = s[s.index("var ICONS = {"):s.index("function icon(n)")]
    icons = {}
    for m in re.finditer(r"^\s+(\w+): (S\('(.*?)'(?:, ([\d.]+))?\)|'(<svg.*?</svg>)')", block, re.M):
        name = m.group(1)
        if m.group(3) is not None:
            icons[name] = svg(m.group(3), m.group(4) or "2.2")
        else:  # 'arrow' is a literal <svg ...>: keep its own stroke width
            raw = m.group(5)
            width = re.search(r'stroke-width="([\d.]+)"', raw).group(1)
            icons[name] = svg(re.search(r"<svg[^>]*>(.*)</svg>", raw).group(1), width)
    if len(icons) != len(re.findall(r"^\s+\w+: ", block, re.M)):
        print("error: some icons were not parsed", file=sys.stderr)
        return 1
    lines = [
        "// GENERATED by app/tools/extract_icons.py from design/prototype.html (ICONS). Do not edit.",
        "// ignore_for_file: unnecessary_raw_strings",
        "",
        "/// SVG source of every prototype icon, by name.",
        "const Map<String, String> isharaIconSvg = {",
    ]
    for name, src in icons.items():
        lines.append(f"  '{name}': r'''{src}''',")
    lines.append("};")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(icons)} icons -> {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
